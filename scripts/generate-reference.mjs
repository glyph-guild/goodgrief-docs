// Generates the CLI and console-key reference pages from the JSON that
// `gg reference --json` prints, and checks that every gg command named
// anywhere in the docs exists in that JSON.
//
// The JSON is a snapshot of a released gg, kept in src/data/gg-reference.json.
// To move it to a newer release, run scripts/refresh-reference.sh <version>.

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const docs = join(root, 'src/content/docs');
const reference = JSON.parse(readFileSync(join(root, 'src/data/gg-reference.json'), 'utf8'));
const version = reference.version.split('+')[0];

const generated = {
	cli: join(docs, 'reference/cli.md'),
	keys: join(docs, 'reference/console-keys.md'),
};

const notice = `<!-- Generated by scripts/generate-reference.mjs from gg ${version}. Do not edit. -->`;

// Markdown table cells cannot hold a bare pipe.
const cell = (text) => text.replaceAll('|', '\\|');

function cliPage() {
	const lines = [
		'---',
		'title: CLI commands',
		`description: Every gg command and option, as gg ${version} lists them.`,
		'sidebar:',
		'  order: 1',
		'---',
		'',
		notice,
		'',
		`This page lists every command in gg ${version}, generated from gg's own help. Run \`gg --help\` for the same list in a terminal.`,
		'',
		'Most commands accept `--json` to print a machine-readable result instead of text.',
		'',
	];

	for (const command of reference.commands) {
		lines.push(`## \`${command.usage}\``, '');
		lines.push(command.summary ? `${capitalise(command.summary)}.` : '', '');

		if (command.options.length > 0) {
			lines.push('| Option | Meaning |', '|---|---|');
			for (const option of command.options) {
				lines.push(`| \`${cell(option.usage)}\` | ${cell(capitalise(option.summary))} |`);
			}
			lines.push('');
		}
	}

	return lines.join('\n');
}

function keysPage() {
	const lines = [
		'---',
		'title: Console keys',
		`description: Every key in the gg console, as gg ${version} defines them.`,
		'sidebar:',
		'  order: 2',
		'---',
		'',
		notice,
		'',
		`This page lists every key in the gg ${version} console, generated from the same list the console's help page draws. In the console, press \`?\` to see it.`,
		'',
		'`ctrl+c` quits from anywhere, and `esc` closes any open window.',
		'',
	];

	const groups = new Map();
	for (const key of reference.keys) {
		const heading = key.heading || 'On the main screen';
		if (!groups.has(heading)) groups.set(heading, []);
		groups.get(heading).push(key);
	}

	for (const [heading, keys] of groups) {
		lines.push(`## ${capitalise(heading)}`, '', '| Key | Action | When |', '|---|---|---|');
		for (const key of keys) {
			lines.push(`| \`${cell(key.key)}\` | ${cell(capitalise(key.does))} | ${cell(key.when ?? '')} |`);
		}
		lines.push('');
	}

	return lines.join('\n');
}

function capitalise(text) {
	return text.length === 0 ? text : text[0].toUpperCase() + text.slice(1);
}

// A docs page may name `gg <words>` only if gg has that command.
function tokens(usage) {
	return usage.split(/\s+/).slice(1);
}

function isPlaceholder(token) {
	return /^[<\[\-]/.test(token);
}

function exists(mention) {
	const words = mention.split(/\s+/).slice(1);
	if (words.length === 0) return true;

	return reference.commands.some((command) => {
		const parts = tokens(command.usage);
		if (parts.length === 0) return false;
		for (let i = 0; i < parts.length; i++) {
			if (isPlaceholder(parts[i])) return i > 0;
			if (i >= words.length) return i > 0;
			if (!parts[i].split('|').includes(words[i])) return false;
		}
		return true;
	});
}

function markdownFiles(directory) {
	return readdirSync(directory).flatMap((name) => {
		const path = join(directory, name);
		if (statSync(path).isDirectory()) return markdownFiles(path);
		return /\.mdx?$/.test(name) ? [path] : [];
	});
}

function unknownMentions() {
	const problems = [];
	const skip = new Set(Object.values(generated));

	for (const file of markdownFiles(docs)) {
		if (skip.has(file)) continue;
		const text = readFileSync(file, 'utf8');
		// Lines inside fenced code blocks, and inline code, that start with gg.
		const fenced = [...text.matchAll(/^```[^\n]*\n([\s\S]*?)^```/gm)].map((m) => m[1]).join('\n');
		const prose = text.replace(/^```[^\n]*\n[\s\S]*?^```/gm, '');
		const mentions = [
			...[...prose.matchAll(/`(gg(?: [a-z][a-z-]*)*)[^`]*`/g)].map((m) => m[1]),
			...[...fenced.matchAll(/^\s*(gg(?: [a-z][a-z-]*)*)/gm)].map((m) => m[1]),
		];
		for (const mention of new Set(mentions)) {
			if (!exists(mention)) problems.push(`${relative(root, file)}: \`${mention}\``);
		}
	}

	return problems;
}

writeFileSync(generated.cli, `${cliPage()}\n`);
writeFileSync(generated.keys, `${keysPage()}\n`);

const problems = unknownMentions();
if (problems.length > 0) {
	console.error(`These pages name gg commands that gg ${version} does not have:`);
	for (const problem of problems) console.error(`  ${problem}`);
	console.error('Correct the page, or refresh the snapshot with scripts/refresh-reference.sh.');
	process.exit(1);
}

console.log(`Generated the CLI and console-key pages from gg ${version}.`);
